
-- BASE DE DATOS PISCICONTROL
-- Sistema de gestion de piscigranjas

-- TABLA USUARIOS
CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    usuario VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    estado VARCHAR(20) DEFAULT 'ACTIVO'
);

-- TABLA ESTANQUES
CREATE TABLE IF NOT EXISTS estanques (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    capacidad INT NOT NULL,
    ubicacion VARCHAR(150),
    estado VARCHAR(20) DEFAULT 'ACTIVO'
);

-- TABLA LOTES DE TRUCHAS
CREATE TABLE IF NOT EXISTS lotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estanque_id BIGINT NOT NULL,
    fecha_ingreso DATE NOT NULL,
    cantidad_truchas INT NOT NULL,
    observaciones VARCHAR(255),

    CONSTRAINT fk_lote_estanque
    FOREIGN KEY (estanque_id)
    REFERENCES estanques(id)
);

-- TABLA DE ALIMENTACION DE TRUCHAS
CREATE TABLE IF NOT EXISTS alimentacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL,
    fecha DATE NOT NULL,
    tipo_alimento VARCHAR(100) NOT NULL,
    cantidad_kg DECIMAL(10,3) NOT NULL,
    observaciones VARCHAR(255),

    CONSTRAINT chk_alimentacion_cantidad
        CHECK (cantidad_kg > 0),

    CONSTRAINT fk_alimentacion_lote
        FOREIGN KEY (lote_id)
        REFERENCES lotes(id)
);

-- TABLA CRECIMIENTO DE TRUCHAS
CREATE TABLE IF NOT EXISTS crecimiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL,
    fecha DATE NOT NULL,
    peso_promedio_g DECIMAL(10,2) NOT NULL,
    talla_promedio_cm DECIMAL(8,2) NOT NULL,
    cantidad_muestra INT NOT NULL,
    observaciones VARCHAR(255),

    CONSTRAINT chk_peso_crecimiento
        CHECK (peso_promedio_g > 0),

    CONSTRAINT chk_talla_crecimiento
        CHECK (talla_promedio_cm > 0),

    CONSTRAINT chk_muestra_crecimiento
        CHECK (cantidad_muestra > 0),

    CONSTRAINT fk_crecimiento_lote
        FOREIGN KEY (lote_id)
        REFERENCES lotes(id)
);

-- TABLA DE PRODUCCION DE TRUCHAS

CREATE TABLE IF NOT EXISTS produccion (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    lote_id BIGINT NOT NULL,

    fecha DATE NOT NULL,

    cantidad_truchas INT NOT NULL,

    peso_total_kg DECIMAL(12,3) NOT NULL,

    estado VARCHAR(20) DEFAULT 'REGISTRADA'
        NOT NULL,

    observaciones VARCHAR(255),

    CONSTRAINT fk_produccion_lote
        FOREIGN KEY (lote_id)
        REFERENCES lotes(id),

    CONSTRAINT chk_produccion_cantidad
        CHECK (cantidad_truchas > 0),

    CONSTRAINT chk_produccion_peso
        CHECK (peso_total_kg > 0),

    CONSTRAINT chk_produccion_estado
        CHECK (estado IN ('REGISTRADA', 'ANULADA'))
);

-- ========================================
-- TABLA DE VENTAS DE TRUCHAS
-- ========================================

CREATE TABLE IF NOT EXISTS ventas (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    produccion_id BIGINT NOT NULL,

    fecha DATE NOT NULL,

    cliente VARCHAR(120) NOT NULL,

    cantidad_kg DECIMAL(12,3) NOT NULL,

    precio_unitario_kg DECIMAL(12,2) NOT NULL,

    total DECIMAL(14,2) NOT NULL,

    estado VARCHAR(20) DEFAULT 'REGISTRADA'
        NOT NULL,

    observaciones VARCHAR(255),

    CONSTRAINT fk_venta_produccion
        FOREIGN KEY (produccion_id)
        REFERENCES produccion(id),

    CONSTRAINT chk_venta_cantidad
        CHECK (cantidad_kg > 0),

    CONSTRAINT chk_venta_precio
        CHECK (precio_unitario_kg > 0),

    CONSTRAINT chk_venta_total
        CHECK (total > 0),

    CONSTRAINT chk_venta_estado
        CHECK (estado IN ('REGISTRADA', 'ANULADA'))
);

-- ==========================================
-- TABLA CALIDAD DEL AGUA
-- Sistema PisciControlF
-- ==========================================

CREATE TABLE IF NOT EXISTS calidad_agua (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    estanque_id BIGINT NOT NULL,

    fecha DATE NOT NULL,

    temperatura_c DECIMAL(5,2) NOT NULL,

    ph DECIMAL(4,2) NOT NULL,

    oxigeno_mg_l DECIMAL(6,2) NOT NULL,

    estado VARCHAR(20) DEFAULT 'SIN_EVALUAR'
        NOT NULL,

    observaciones VARCHAR(255),

    CONSTRAINT fk_calidad_estanque
        FOREIGN KEY (estanque_id)
        REFERENCES estanques(id),

    CONSTRAINT chk_calidad_ph
        CHECK (ph >= 0 AND ph <= 14),

    CONSTRAINT chk_calidad_oxigeno
        CHECK (oxigeno_mg_l >= 0),

    CONSTRAINT chk_calidad_estado
        CHECK (
            estado IN (
                'SIN_EVALUAR',
                'NORMAL',
                'ALERTA',
                'CRITICO'
            )
        )
);

-- ==========================================
-- TABLA MORTALIDAD Y SANIDAD
-- Sistema PisciControlF
-- ==========================================

CREATE TABLE IF NOT EXISTS mortalidad (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    lote_id BIGINT NOT NULL,

    fecha DATE NOT NULL,

    tipo_incidencia VARCHAR(20) NOT NULL,

    cantidad_muertas INT DEFAULT 0 NOT NULL,

    causa VARCHAR(120),

    estado VARCHAR(20) DEFAULT 'ABIERTA' NOT NULL,

    acciones VARCHAR(500),

    observaciones VARCHAR(500),

    CONSTRAINT fk_mortalidad_lote
        FOREIGN KEY (lote_id)
        REFERENCES lotes(id),

    CONSTRAINT chk_mortalidad_tipo
        CHECK (
            tipo_incidencia IN (
                'MORTALIDAD',
                'SANIDAD'
            )
        ),

    CONSTRAINT chk_mortalidad_cantidad
        CHECK (
            cantidad_muertas >= 0
            AND (
                tipo_incidencia <> 'MORTALIDAD'
                OR cantidad_muertas > 0
            )
        ),

    CONSTRAINT chk_mortalidad_estado
        CHECK (
            estado IN (
                'ABIERTA',
                'CERRADA'
            )
        )
);


